//! The local engine's per-install bearer token.
//!
//! Engines built from Sovereign Intelligence Core main refuse a request
//! without `Authorization: Bearer <token>`. The SI wizard (DRA-56) keeps the
//! token at `~/.local/share/aienos/auth/bearer-token` and hands it to the
//! engine as `AIEN_SERVE_HTTP_BEARER_TOKEN`. The volunteer reads the same file
//! and makes the same checks the wizard makes (`installer/wizard/net.om`,
//! `tkload`): the folder is a real folder of this user with mode 0700, the
//! file is a regular file of this user with mode 0600, neither is a link, and
//! the file is exactly 64 lowercase hex digits and a newline.
//!
//! The check itself is Omega: `om/tkcheck.om`, compiled into this crate and
//! called in-process through omega-bridge's native ABI v2 (`om/gen`, built by
//! `build.rs`, regenerated by `om/regen.sh`). It is built for AArch64 Linux
//! only; elsewhere an existing token file is refused.
//!
//! The token is never printed: its `Debug` form is redacted, errors name
//! only the path and the failed check, and the bytes are zeroed on drop.

use std::fmt;
use std::path::{Path, PathBuf};

/// Where the SI wizard writes the token, relative to `$HOME`.
pub const TOKEN_HOME_PATH: &str = ".local/share/aienos/auth/bearer-token";

const TOKEN_HEX: usize = 64;

/// 64 lowercase hex digits, the value sent after `Bearer `.
#[derive(Clone)]
pub struct BearerToken([u8; TOKEN_HEX]);

impl BearerToken {
    /// The header value's token part. Always ASCII hex.
    pub fn as_str(&self) -> &str {
        std::str::from_utf8(&self.0).expect("checked to be ASCII hex on load")
    }
}

impl fmt::Debug for BearerToken {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("BearerToken(<redacted>)")
    }
}

impl Drop for BearerToken {
    fn drop(&mut self) {
        self.0.fill(0);
    }
}

#[derive(Debug, thiserror::Error, PartialEq, Eq)]
pub enum TokenError {
    #[error("{0}")]
    NotPrivate(String),
    #[error("{0} is not 64 lowercase hex digits and a newline")]
    Malformed(String),
    #[error("{0}: {1}")]
    Io(String, String),
}

/// `$HOME/.local/share/aienos/auth/bearer-token`, or `None` without `$HOME`.
pub fn default_token_path() -> Option<PathBuf> {
    let home = std::env::var_os("HOME").filter(|h| !h.is_empty())?;
    Some(PathBuf::from(home).join(TOKEN_HOME_PATH))
}

#[cfg(oh_tkcheck)]
mod om {
    include!("../om/gen/omega_native.rs");
}

/// The bridge status and `tkcheck`'s result code and detail.
#[cfg(oh_tkcheck)]
fn tkcheck(dir: &[u8], file: &[u8], tok: &mut [u8; TOKEN_HEX]) -> (u32, i64, u64) {
    let mut result = 0u64;
    let mut info = [0u64; 1];
    // SAFETY: the pointers are live for the call and their lengths are the
    // ones passed; `tok` and `info` have the exact lengths the export
    // declares (64 bytes, one ulong). The bridge refuses anything else with
    // status 32 and writes `result` only on status 0.
    let st = unsafe {
        om::omega2_tkcheck(
            &mut result,
            dir.as_ptr(),
            dir.len() as u64,
            file.as_ptr(),
            file.len() as u64,
            tok.as_mut_ptr(),
            info.as_mut_ptr(),
        )
    };
    (st, result as i64, info[0])
}

#[cfg(not(oh_tkcheck))]
fn tkcheck(_dir: &[u8], file: &[u8], _tok: &mut [u8; TOKEN_HEX]) -> (u32, i64, u64) {
    use std::os::unix::ffi::OsStrExt;
    // No Omega code for this target: report only whether a file is there.
    let p = Path::new(std::ffi::OsStr::from_bytes(file));
    match std::fs::symlink_metadata(p) {
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => (0, 1, 0),
        _ => (0, -1, 0),
    }
}

fn os_error(errno: u64) -> String {
    std::io::Error::from_raw_os_error(i32::try_from(errno).unwrap_or(i32::MAX)).to_string()
}

/// Loads the token at `path`.
///
/// `Ok(None)` when there is no file there: the shipped engine needs no
/// token, so the caller sends none. An existing file that fails any check is
/// an error, never silently skipped.
pub fn load_bearer_token(path: &Path) -> Result<Option<BearerToken>, TokenError> {
    use std::os::unix::ffi::OsStrExt;
    let dir = match path.parent() {
        Some(d) if !d.as_os_str().is_empty() => d,
        _ => Path::new("."),
    };
    let shown = path.display().to_string();
    let (d, f) = (dir.as_os_str().as_bytes(), path.as_os_str().as_bytes());
    if f.contains(&0) {
        return Err(TokenError::Io(shown, "the path contains a NUL byte".into()));
    }
    let mut tok = [0u8; TOKEN_HEX];
    let (st, code, info) = tkcheck(d, f, &mut tok);
    if st != 0 || code != 0 {
        tok.fill(0);
    }
    if st != 0 {
        return Err(TokenError::Io(
            shown,
            format!("the Omega token check stopped with status {st}"),
        ));
    }
    let (at, kind, mode) = if code < 20 {
        (dir.display().to_string(), "folder", 0o700)
    } else {
        (shown.clone(), "file", 0o600)
    };
    Err(match code {
        0 => return Ok(Some(BearerToken(tok))),
        1 => return Ok(None),
        10 | 20 => TokenError::Io(at, os_error(info)),
        11 | 21 => TokenError::NotPrivate(format!(
            "{at} is a link; the token {kind} must be a real {kind}"
        )),
        12 | 22 => TokenError::NotPrivate(format!("{at} is not a {kind}")),
        13 | 23 => TokenError::NotPrivate(format!("{at} belongs to uid {info}, not to this user")),
        14 | 24 => TokenError::NotPrivate(format!(
            "{at} has mode {info:04o}; it must be {mode:04o} (run: chmod {mode:o} {at})"
        )),
        30 | 35 => TokenError::Malformed(shown),
        31 | 32 | 34 => TokenError::Io(shown, os_error(info)),
        33 => TokenError::NotPrivate(format!("{shown} changed while it was being checked")),
        -1 => TokenError::Io(
            shown,
            "the token check is Omega code built for AArch64 Linux only; this build cannot read the token".into(),
        ),
        c => TokenError::Io(shown, format!("the Omega token check returned unknown code {c}")),
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::os::unix::fs::PermissionsExt;

    const GOOD: &str = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef\n";

    struct Tmp(PathBuf);
    impl Drop for Tmp {
        fn drop(&mut self) {
            let _ = std::fs::remove_dir_all(&self.0);
        }
    }

    /// A temp root with `auth/` (mode `dmode`) holding `bearer-token` (mode
    /// `fmode`) with `text`. Returns the root guard and the file path.
    fn setup(text: &[u8], dmode: u32, fmode: u32) -> (Tmp, PathBuf) {
        use rand::RngCore;
        let root = std::env::temp_dir().join(format!(
            "oh-infer-bearer-{}-{}",
            std::process::id(),
            rand::thread_rng().next_u64()
        ));
        let dir = root.join("auth");
        std::fs::create_dir_all(&dir).unwrap();
        let file = dir.join("bearer-token");
        std::fs::write(&file, text).unwrap();
        std::fs::set_permissions(&file, std::fs::Permissions::from_mode(fmode)).unwrap();
        std::fs::set_permissions(&dir, std::fs::Permissions::from_mode(dmode)).unwrap();
        (Tmp(root), file)
    }

    #[test]
    fn loads_the_wizards_file() {
        let (_t, f) = setup(GOOD.as_bytes(), 0o700, 0o600);
        let tok = load_bearer_token(&f).unwrap().unwrap();
        assert_eq!(tok.as_str(), GOOD.trim_end());
    }

    #[test]
    fn missing_file_is_no_token() {
        let (_t, f) = setup(GOOD.as_bytes(), 0o700, 0o600);
        assert_eq!(
            load_bearer_token(&f.with_file_name("absent"))
                .unwrap()
                .map(|_| ()),
            None
        );
        assert!(
            load_bearer_token(Path::new("/nonexistent-oh-infer/auth/bearer-token"))
                .unwrap()
                .is_none()
        );
    }

    #[test]
    fn refuses_a_file_others_can_read() {
        for mode in [0o644, 0o640, 0o604, 0o400, 0o660] {
            let (_t, f) = setup(GOOD.as_bytes(), 0o700, mode);
            let e = load_bearer_token(&f).unwrap_err();
            assert!(matches!(e, TokenError::NotPrivate(_)), "{mode:o}: {e:?}");
            assert!(!e.to_string().contains(GOOD.trim_end()));
        }
    }

    #[test]
    fn refuses_a_folder_others_can_enter() {
        for mode in [0o755, 0o750, 0o711] {
            let (_t, f) = setup(GOOD.as_bytes(), mode, 0o600);
            assert!(matches!(
                load_bearer_token(&f),
                Err(TokenError::NotPrivate(_))
            ));
        }
    }

    #[test]
    fn names_the_mode_to_fix() {
        let (_t, f) = setup(GOOD.as_bytes(), 0o700, 0o640);
        let e = load_bearer_token(&f).unwrap_err().to_string();
        let p = f.display();
        assert_eq!(
            e,
            format!("{p} has mode 0640; it must be 0600 (run: chmod 600 {p})")
        );
        let (_t, f) = setup(GOOD.as_bytes(), 0o750, 0o600);
        let e = load_bearer_token(&f).unwrap_err().to_string();
        let d = f.parent().unwrap().display();
        assert_eq!(
            e,
            format!("{d} has mode 0750; it must be 0700 (run: chmod 700 {d})")
        );
    }

    #[test]
    fn refuses_a_socket_in_place_of_the_file() {
        let (_t, f) = setup(GOOD.as_bytes(), 0o700, 0o600);
        std::fs::remove_file(&f).unwrap();
        let _s = std::os::unix::net::UnixListener::bind(&f).unwrap();
        std::fs::set_permissions(&f, std::fs::Permissions::from_mode(0o600)).unwrap();
        let e = load_bearer_token(&f).unwrap_err();
        assert_eq!(
            e,
            TokenError::NotPrivate(format!("{} is not a file", f.display()))
        );
    }

    /// The compiled check is the one built from `om/tkcheck.om` as it is now.
    #[cfg(oh_tkcheck)]
    #[test]
    fn binding_matches_its_source() {
        use sha2::Digest;
        let src = sha2::Sha256::digest(include_bytes!("../om/tkcheck.om"));
        let hex: String = src.iter().map(|b| format!("{b:02x}")).collect();
        assert!(
            om::OMEGA2_IDENT_tkcheck.contains(&format!(" src={hex} ")),
            "om/gen is stale: run om/regen.sh"
        );
        // SAFETY: the bridge returns a static NUL-terminated string.
        let live = unsafe { std::ffi::CStr::from_ptr(om::omega2_ident_tkcheck().cast()) };
        assert_eq!(live.to_str().unwrap(), om::OMEGA2_IDENT_tkcheck);
        let txt = include_str!("../om/gen/ident.txt");
        assert!(txt.starts_with(om::OMEGA2_IDENT_tkcheck), "{txt}");
    }

    #[test]
    fn refuses_malformed_contents() {
        let upper = GOOD.to_uppercase();
        let no_nl = &GOOD[..64];
        let short = &GOOD[2..];
        let crlf = format!("{}\r\n", &GOOD[..63]);
        let extra = format!("{GOOD}\n");
        let nonhex = format!("{}g\n", &GOOD[..63]);
        for text in [&upper[..], no_nl, short, &crlf, &extra, &nonhex, ""] {
            let (_t, f) = setup(text.as_bytes(), 0o700, 0o600);
            let e = load_bearer_token(&f).unwrap_err();
            assert!(matches!(e, TokenError::Malformed(_)), "{text:?}: {e:?}");
        }
    }

    #[test]
    fn refuses_a_link() {
        let (_t, f) = setup(GOOD.as_bytes(), 0o700, 0o600);
        let link = f.with_file_name("link");
        std::os::unix::fs::symlink(&f, &link).unwrap();
        assert!(matches!(
            load_bearer_token(&link),
            Err(TokenError::NotPrivate(_))
        ));
    }

    #[test]
    fn debug_never_shows_the_token() {
        let (_t, f) = setup(GOOD.as_bytes(), 0o700, 0o600);
        let tok = load_bearer_token(&f).unwrap().unwrap();
        let shown = format!("{tok:?}");
        assert!(!shown.contains(&GOOD[..16]), "{shown}");
    }
}
